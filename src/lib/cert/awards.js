export const ALL_AWARDS = AUDIENCES.flatMap((a) => a.awards.map(([title, reason]) => ({ title, reason, audience: a.id })));

/** Find an award by title, ignoring case and spaces at the ends. */
export function findAward(title) {
  const t = String(title || '').trim().toLowerCase();
  if (!t) return null;
  return ALL_AWARDS.find((a) => a.title.toLowerCase() === t) || null;
}
